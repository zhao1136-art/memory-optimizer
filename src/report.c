static const char *severity_str(int sev) {
    if (sev >= 4) return "高";
    if (sev >= 2) return "中";
    return "低";
}

static char *dup_s(const char *s) {
    size_t n = strlen(s);
    char *r = (char*)malloc(n + 1);
    if (r) memcpy(r, s, n + 1);
    return r;
}

static char *html_escape_tmp(char *buf, size_t n, const char *in) {
    size_t o = 0;
    for (const unsigned char *p = (const unsigned char*)in; *p && o + 6 < n; p++) {
        if (*p == '<') { memcpy(buf + o, "&lt;", 4); o += 4; }
        else if (*p == '>') { memcpy(buf + o, "&gt;", 4); o += 4; }
        else if (*p == '&') { memcpy(buf + o, "&amp;", 5); o += 5; }
        else buf[o++] = (char)*p;
    }
    buf[o] = '\0';
    return buf;
}

char *report_build_html(sampler *s) {
    strbuf b; sb_init(&b, 1 << 16);
    char esc[512];

    sys_mem sy;
    sampler_lock(s);
    sy = s->sys;
    long uptime = (long)((now_ms() - s->started_ms) / 1000);

    /* 热点 */
    hotspot_item hh[15];
    int hn = hotspot_rank(s, "private", 15, hh, 15);
    /* 泄漏 */
    leak_item li[10];
    int ln = leak_detect(s, li, 10);
    /* 建议 */
    suggest_item sug[20];
    int sn = optimize_analyze(s, sug, 20);
    sampler_unlock(s);

    sb_puts(&b, "<!DOCTYPE html><html lang=\"zh\"><head><meta charset=\"utf-8\">");
    sb_puts(&b, "<title>内存优化工具 - 报告</title></head><body style=\"font-family:sans-serif;margin:24px;color:#222;\">");
    sb_printf(&b, "<h1>内存优化报告</h1><p>生成时间：%llu ms | 运行时长：%ld 秒 | 采样数：%llu</p>",
              (unsigned long long)wall_ms(), uptime, (unsigned long long)s->sample_count);

    /* 系统总览 */
    sb_puts(&b, "<h2>一、系统总览</h2><table border=\"1\" cellpadding=\"6\" cellspacing=\"0\" style=\"border-collapse:collapse\">");
    sb_printf(&b, "<tr><td><b>物理内存总量</b></td><td>%.0f MB</td></tr>",
              (double)sy.phys_total / 1048576.0);
    sb_printf(&b, "<tr><td><b>可用物理内存</b></td><td>%.0f MB（%.1f%%）</td></tr>",
              (double)sy.phys_avail / 1048576.0,
              sy.phys_total ? (double)sy.phys_avail / sy.phys_total * 100 : 0);
    sb_printf(&b, "<tr><td><b>提交限额/已用</b></td><td>%.0f / %.0f MB</td></tr>",
              (double)sy.commit_used / 1048576.0, (double)sy.commit_limit / 1048576.0);
    sb_printf(&b, "<tr><td><b>缓存/standby</b></td><td>%.0f MB</td></tr>",
              (double)sy.cache_bytes / 1048576.0);
    sb_printf(&b, "<tr><td><b>系统句柄/线程</b></td><td>%u / %u</td></tr>",
              sy.handle_count, sy.thread_count);
    sb_puts(&b, "</table>");

    /* 热点 */
    sb_puts(&b, "<h2>二、内存占用热点分析（按私有字节 Top）</h2>");
    sb_puts(&b, "<table border=\"1\" cellpadding=\"6\" cellspacing=\"0\" style=\"border-collapse:collapse\">");
    sb_puts(&b, "<tr><th>排名</th><th>进程</th><th>运行时</th><th>私有(MB)</th><th>工作集(MB)</th><th>峰值(MB)</th><th>占比</th></tr>");
    for (int i = 0; i < hn; i++) {
        sb_printf(&b, "<tr><td>%d</td><td>%s</td><td>%s</td><td>%.2f</td><td>%.2f</td><td>%.2f</td><td>%.1f%%</td></tr>",
                  i + 1, html_escape_tmp(esc, sizeof esc, hh[i].name),
                  runtime_label((rt_kind)hh[i].rt), hh[i].private_mb, hh[i].ws_mb,
                  hh[i].peak_mb, hh[i].share * 100);
    }
    sb_puts(&b, "</table>");

    /* 泄漏 */
    sb_puts(&b, "<h2>三、泄漏检测</h2>");
    if (ln == 0) sb_puts(&b, "<p>未发现明显泄漏趋势。</p>");
    else {
        sb_puts(&b, "<table border=\"1\" cellpadding=\"6\" cellspacing=\"0\" style=\"border-collapse:collapse\">");
        sb_puts(&b, "<tr><th>进程</th><th>类型</th><th>速率(KB/min)</th><th>R²</th><th>历时(秒)</th><th>严重度</th></tr>");
        for (int i = 0; i < ln; i++) {
            const char *k = li[i].kind == 0 ? "私有字节" : "句柄";
            sb_printf(&b, "<tr><td>%s</td><td>%s</td><td>%.1f</td><td>%.2f</td><td>%.0f</td><td>%s</td></tr>",
                      html_escape_tmp(esc, sizeof esc, li[i].name), k,
                      li[i].slope_kb_per_min, li[i].r2, li[i].time_span_sec,
                      severity_str(li[i].severity));
        }
        sb_puts(&b, "</table>");
    }

    /* 建议 */
    sb_puts(&b, "<h2>四、内存优化建议</h2>");
    if (sn == 0) sb_puts(&b, "<p>当前无明显优化项。</p>");
    else {
        sb_puts(&b, "<ul>");
        for (int i = 0; i < sn; i++) {
            sb_printf(&b, "<li><b>[%s] %s</b><br>%s</li>",
                      severity_str(sug[i].severity),
                      html_escape_tmp(esc, sizeof esc, sug[i].title),
                      html_escape_tmp(esc, sizeof esc, sug[i].reason));
        }
        sb_puts(&b, "</ul>");
    }

    sb_puts(&b, "<p style=\"margin-top:24px;color:#888\">Generated by Memory Optimizer. 纯 C 原生 / 低开销。</p>");
    sb_puts(&b, "</body></html>");
    char *r = dup_s(sb_cstr(&b));
    sb_free(&b);
    return r;
}

char *report_build_csv(sampler *s, uint32_t pid) {
    sampler_lock(s);
    sseries *se = pid == 0 ? s->sys_series : sampler_find_series(s, pid);
    strbuf b; sb_init(&b, 1 << 14);
    if (!se) {
        sb_puts(&b, "error,no data or process not found\n");
    } else {
        if (pid == 0)
            sb_puts(&b, "ts_ms,avail_bytes,commit_used,cache_bytes,handles\n");
        else
            sb_puts(&b, "ts_ms,private_bytes,working_set,handles,cpu_ms\n");
        int cap = (int)se->len;
        if (cap > 10000) cap = 10000;
        int n = series_export(se, NULL, NULL, NULL, NULL, cap);

        uint32_t first_idx = (se->head + se->cap - se->len) % se->cap;
        uint32_t skip = se->len > (uint32_t)cap ? (uint32_t)(se->len - cap) : 0;
        uint32_t start = (first_idx + skip) % se->cap;
        (void)n;
        for (int i = 0; i < cap; i++) {
            uint32_t idx = (start + (uint32_t)i) % se->cap;
            if (pid == 0)
                sb_printf(&b, "%.0f,%.0f,%.0f,%.0f,%.0f\n",
                          se->ts[idx], se->priv[idx], se->ws[idx], se->handles[idx], se->faults[idx]);
            else
                sb_printf(&b, "%.0f,%.0f,%.0f,%.0f,%.0f\n",
                          se->ts[idx], se->priv[idx], se->ws[idx], se->handles[idx], se->cpu[idx]);
        }
    }
    sampler_unlock(s);
    char *r = dup_s(sb_cstr(&b));
    sb_free(&b);
    return r;
}

char *report_build_json(sampler *s) {
    sampler_lock(s);
    sys_mem sy = s->sys;
    hotspot_item hh[15]; int hn = hotspot_rank(s, "private", 15, hh, 15);
    leak_item li[10];    int ln = leak_detect(s, li, 10);
    suggest_item sug[20];int sn = optimize_analyze(s, sug, 20);

    json j; json_init(&j, 1 << 14);
    j_begin_obj(&j);
    j_key(&j, "generated_ms"); j_uint(&j, wall_ms());
    /* 采样器 */
    j_key(&j, "sampler"); j_begin_obj(&j);
    j_key(&j, "interval_ms"); j_int(&j, s->cfg.interval_ms);
    j_key(&j, "window_size"); j_int(&j, s->cfg.window_size);
    j_key(&j, "sample_count"); j_uint(&j, s->sample_count);
    j_key(&j, "uptime_s"); j_int(&j, (int64_t)((now_ms() - s->started_ms) / 1000));
    j_end(&j);
    /* 系统 */
    j_key(&j, "system"); j_begin_obj(&j);
    j_key(&j, "total_mb"); j_dbl(&j, (double)sy.phys_total / 1048576.0);
    j_key(&j, "avail_mb"); j_dbl(&j, (double)sy.phys_avail / 1048576.0);
    j_key(&j, "avail_pct"); j_dbl(&j, sy.phys_total ? (double)sy.phys_avail / sy.phys_total * 100 : 0);
    j_key(&j, "commit_used_mb"); j_dbl(&j, (double)sy.commit_used / 1048576.0);
    j_key(&j, "commit_limit_mb"); j_dbl(&j, (double)sy.commit_limit / 1048576.0);
    j_key(&j, "cache_mb"); j_dbl(&j, (double)sy.cache_bytes / 1048576.0);
    j_key(&j, "handles"); j_uint(&j, sy.handle_count);
    j_key(&j, "threads"); j_uint(&j, sy.thread_count);
    j_end(&j);
    /* 热点 */
    j_key(&j, "hotspots"); j_begin_arr(&j);
    for (int i = 0; i < hn; i++) {
        j_begin_obj(&j);
        j_key(&j, "pid"); j_uint(&j, hh[i].pid);
        j_key(&j, "name"); j_str(&j, hh[i].name);
        j_key(&j, "runtime"); j_str(&j, runtime_label((rt_kind)hh[i].rt));
        j_key(&j, "private_mb"); j_dbl(&j, hh[i].private_mb);
        j_key(&j, "ws_mb"); j_dbl(&j, hh[i].ws_mb);
        j_key(&j, "peak_mb"); j_dbl(&j, hh[i].peak_mb);
        j_key(&j, "cpu_pct"); j_dbl(&j, hh[i].cpu_pct);
        j_key(&j, "threads"); j_uint(&j, hh[i].threads);
        j_key(&j, "handles"); j_uint(&j, hh[i].handle_count);
        j_key(&j, "share"); j_dbl(&j, hh[i].share);
        j_end(&j);
    }
    j_end(&j);
    /* 泄漏 */
    j_key(&j, "leaks"); j_begin_arr(&j);
    for (int i = 0; i < ln; i++) {
        j_begin_obj(&j);
        j_key(&j, "pid"); j_uint(&j, li[i].pid);
        j_key(&j, "name"); j_str(&j, li[i].name);
        j_key(&j, "kind"); j_str(&j, li[i].kind == 0 ? "private" : "handles");
        j_key(&j, "slope_kb_per_min"); j_dbl(&j, li[i].slope_kb_per_min);
        j_key(&j, "r2"); j_dbl(&j, li[i].r2);
        j_key(&j, "last_mb"); j_dbl(&j, li[i].last_mb);
        j_key(&j, "cpu_pct"); j_dbl(&j, li[i].cpu_pct);
        j_key(&j, "samples"); j_int(&j, li[i].samples);
        j_key(&j, "time_span_sec"); j_dbl(&j, li[i].time_span_sec);
        j_key(&j, "severity"); j_str(&j, severity_str(li[i].severity));
        j_end(&j);
    }
    j_end(&j);
    /* 建议 */
    j_key(&j, "suggestions"); j_begin_arr(&j);
    for (int i = 0; i < sn; i++) {
        j_begin_obj(&j);
        j_key(&j, "severity"); j_str(&j, severity_str(sug[i].severity));
        j_key(&j, "kind"); j_int(&j, (int)sug[i].kind);
        j_key(&j, "pid"); j_uint(&j, sug[i].pid);
        j_key(&j, "name"); j_str(&j, sug[i].name);
        j_key(&j, "title"); j_str(&j, sug[i].title);
        j_key(&j, "reason"); j_str(&j, sug[i].reason);
        j_key(&j, "actionable"); j_bool(&j, sug[i].actionable);
        j_key(&j, "action"); j_str(&j, sug[i].action[0] ? sug[i].action : "");
        j_end(&j);
    }
    j_end(&j);
    /* 进程列表 */
    j_key(&j, "processes"); j_begin_arr(&j);
    for (int i = 0; i < s->nprocs; i++) {
        proc_snap *p = &s->procs[i];
        j_begin_obj(&j);
        j_key(&j, "pid"); j_uint(&j, p->pid);
        j_key(&j, "name"); j_str(&j, p->name);
        j_key(&j, "runtime"); j_str(&j, runtime_label((rt_kind)p->rt));
        j_key(&j, "private_mb"); j_dbl(&j, MT_MB(p->private_bytes));
        j_key(&j, "ws_mb"); j_dbl(&j, MT_MB(p->working_set));
        j_key(&j, "peak_mb"); j_dbl(&j, MT_MB(p->peak_working_set));
        j_end(&j);
    }
    j_end(&j);
    j_end(&j);

    size_t len = json_len(&j);
    char *r = (char*)malloc(len + 1);
    if (r) { memcpy(r, json_cstr(&j), len + 1); }
    json_dtor(&j);
    sampler_unlock(s);
    return r;
}

